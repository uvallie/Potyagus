"""Кризовий запобіжник. Спрацьовує ДО виклику LLM: якщо людині погано, гусь не тисне і дає контакти.

Список гарячих ліній перевірити перед запуском на людях: номери й графіки можуть змінитися.
"""
import re

HOTLINES = (
    "• Lifeline Ukraine, запобігання самогубствам: 7333 (цілодобово, безкоштовно)",
    "• Ла Страда, домашнє і гендерне насильство: 116 123",
    "• Дитяча лінія Ла Страда: 116 111",
    "• Якщо є пряма загроза життю: 112",
)

# Корені слів, а не точні фрази: людина в кризі пише як завгодно. Краще зайвий раз бути м'яким.
_PATTERNS = [
    r"самогуб", r"суїцид", r"вбити себе", r"убити себе", r"покінчити з собою", r"накласти на себе руки",
    r"не хочу жити", r"не хочеться жити", r"жити не хочу", r"нема сенсу жити", r"немає сенсу жити",
    r"краще б мене не було", r"хочу померти", r"хочу зникнути назавжди", r"порізати себе", r"ріжу себе",
    r"зашкодити собі", r"мене б'є", r"мене бʼє", r"він мене б", r"насильств",
    r"суицид", r"не хочу жить", r"убить себя", r"покончить с собой",
    r"kill myself", r"suicid", r"want to die", r"self[- ]harm", r"hurt myself",
]
_RE = re.compile("|".join(_PATTERNS), re.IGNORECASE)


def is_crisis(text: str) -> bool:
    return bool(_RE.search(text or ""))


def crisis_reply() -> str:
    return (
        "Я тут. Жодних вправ і жодних «встань» зараз.\n\n"
        "Те, що ти пишеш, звучить дуже важко. Я лише гусь, і тут потрібна жива людина, яка вміє допомогти. "
        "Будь ласка, напиши або подзвони:\n\n"
        + "\n".join(HOTLINES)
        + "\n\nЯкщо поруч є хтось, кому довіряєш, скажи йому просто зараз. Я нікуди не дінусь."
    )
